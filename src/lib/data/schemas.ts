/**
 * The shape of every piece of content the site renders, checked at build time.
 *
 * Each schema is typed against the TypeScript type the components already use (`z.ZodType<Project>`), so
 * the two can't drift: change one without the other and `astro check` fails. Objects are strict, so a
 * misspelled or unknown field ("summmary") fails the build instead of silently disappearing. Whatever data source is
 * active (local files today, a database later) must return data that passes these, or the build stops
 * with a message naming the bad field.
 */
import { z } from "astro/zod";
import type { Project } from "@/data/projects";
import type { CV } from "@/data/cv";
import type { ToolGroup, Swatch } from "@/data/tools";
import type { Shop, Independent } from "@/lib/timpla";

// ───────── Portfolio ─────────
const tint = z.enum(["rosas", "ube", "pandan", "mangga"]);
const swatch: z.ZodType<Swatch> = z.enum(["rosas", "ube", "pandan", "mangga", "langit"]);
const yearMonth = z.string().regex(/^\d{4}(-\d{2})?$/, 'use "YYYY" or "YYYY-MM"');

export const projectSchema: z.ZodType<Project> = z.strictObject({
  title: z.string().min(1),
  year: z.number().int(),
  period: z.string().optional(),
  kind: z.enum(["work", "personal"]),
  org: z.string().optional(),
  categories: z.array(z.enum(["agents", "automation", "rag", "prompting", "evals", "data"])).min(1),
  description: z.string().min(1),
  summary: z.string().optional(),
  results: z.array(z.string()).optional(),
  tags: z.array(z.string()),
  tint,
  preview: z.array(z.string()),
  links: z.array(z.strictObject({ label: z.string(), href: z.string() })),
  featured: z.boolean().optional(),
  media: z.strictObject({
    poster: z.string().startsWith("/"),
    alt: z.string().min(10, "describe what the image shows"),
    width: z.number().int().positive(),
    height: z.number().int().positive(),
  }).optional(),
  caseStudy: z.strictObject({
    slug: z.string().regex(/^[a-z0-9-]+$/),
    tagline: z.string().min(1),
    role: z.string().min(1),
    problem: z.strictObject({ headline: z.string().min(1), body: z.array(z.string()).min(1) }),
    architecture: z.strictObject({
      caption: z.string(),
      stages: z.array(z.strictObject({
        title: z.string(),
        nodes: z.array(z.strictObject({ label: z.string(), tech: z.string(), note: z.string().optional() })).min(1),
      })).min(2),
      loop: z.string().optional(),
    }),
    solution: z.array(z.string()).min(1),
    evals: z.strictObject({
      method: z.array(z.string()).min(1),
      metrics: z.array(z.strictObject({ value: z.string(), label: z.string(), note: z.string() })).min(1),
      caveat: z.string().optional(),
    }),
  }).optional(),
});
export const projectsSchema = z.array(projectSchema).superRefine((list, ctx) => {
  const seen = new Set<string>();
  list.forEach((p, i) => {
    const slug = p.caseStudy?.slug;
    if (!slug) return;
    if (seen.has(slug)) ctx.addIssue({ code: "custom", path: [i, "caseStudy", "slug"], message: `duplicate case-study slug "${slug}"` });
    seen.add(slug);
  });
});

export const cvSchema: z.ZodType<CV> = z.strictObject({
  profile: z.strictObject({
    fullName: z.string(),
    title: z.string(),
    location: z.string(),
    email: z.email(),
    phone: z.string().nullable(),
    summary: z.string(),
    pdf: z.string().nullable(),
  }),
  impact: z.array(z.strictObject({ value: z.string(), label: z.string(), note: z.string() })),
  experience: z.array(z.strictObject({
    company: z.string(),
    title: z.string(),
    location: z.string(),
    start: yearMonth,
    end: yearMonth.nullable(),
    bullets: z.array(z.string()),
    stack: z.array(z.string()).optional(),
  })),
  education: z.array(z.strictObject({
    school: z.string(), degree: z.string(), honours: z.string(), location: z.string(), start: z.string(), end: z.string(),
  })),
  skills: z.array(z.strictObject({ group: z.string(), items: z.array(z.string()) })),
  certifications: z.array(z.strictObject({ name: z.string(), issuer: z.string() })),
  languages: z.array(z.strictObject({ name: z.string(), level: z.string() })),
});

export const toolsSchema = z.strictObject({
  setup: z.array(z.strictObject({ label: z.string(), value: z.string() })),
  toolGroups: z.array(z.strictObject({ title: z.string(), description: z.string(), swatch, items: z.array(z.string()) }) satisfies z.ZodType<ToolGroup>),
  toolboxHighlights: z.array(z.strictObject({ label: z.string(), swatch })),
});

// ───────── Timpla (generated by scripts/build-timpla-data.ts) ─────────
const tier = z.enum(["acclaimed", "recognised", "indie"]);

export const shopSchema: z.ZodType<Shop> = z.strictObject({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string(),
  tier,
  type: z.string(),
  ownership: z.string(),
  beans: z.string(),
  since: z.string(),
  endorsements: z.number(),
  sources: z.array(z.strictObject({ outlet: z.string(), url: z.url() })),
  signals: z.array(z.string()),
  specialty: z.string(),
  status: z.string(),
  website: z.string(),
  instagram: z.string(),
  branches: z.array(z.strictObject({
    name: z.string(),
    neighbourhood: z.string(),
    city: z.string(),
    address: z.string(),
    lat: z.number().nullable(),
    lon: z.number().nullable(),
    coordSource: z.string(),
  })).min(1),
});

export const independentSchema: z.ZodType<Independent> = z.strictObject({
  id: z.string().regex(/^[nwr]\d+$/, "an OpenStreetMap id like n123 / w456"),
  name: z.string(),
  cls: z.enum(["independent", "multibranch"]),
  city: z.string(),
  lon: z.number(),
  lat: z.number(),
  n: z.number(),
  ev: z.enum(["osm_check", "overture_2026_09"]),
  evd: z.string(),
  ig: z.string(),
  web: z.string(),
});

export const pointSchema = z.strictObject({
  slug: z.string(), name: z.string(), branch: z.string(), tier, city: z.string(), nb: z.string(),
  type: z.string(), own: z.enum(["local", "foreign"]), beans: z.string(), since: z.string(),
  lon: z.number(), lat: z.number(), xy: z.tuple([z.number(), z.number()]),
});
export type Point = z.infer<typeof pointSchema>;

export const timplaMetaSchema = z.strictObject({
  builtAt: z.string(),
  shops: z.number(),
  branches: z.number(),
  mapped: z.number(),
  tiers: z.record(tier, z.number()),
  roasterLinks: z.number(),
  beanListings: z.number(),
  listingTotal: z.number(),
  arabicaTotal: z.number(),
  allTotal: z.number(),
  directory: z.strictObject({
    shops: z.number(),
    branches: z.number(),
    classes: z.strictObject({ specialty: z.number(), independent: z.number(), multibranch: z.number() }),
    evidence: z.record(z.string(), z.number()),
    unverified: z.number(),
  }),
});
export type TimplaMeta = z.infer<typeof timplaMetaSchema>;

export const timelineSchema = z.strictObject({
  years: z.array(z.strictObject({ year: z.number(), opened: z.number(), openedIncluded: z.number(), closed: z.number() })),
  events: z.number(),
});
export const provenanceSchema = z.array(z.strictObject({
  province: z.string(), listings: z.number(), menuShare: z.number(),
  arabicaTonnes: z.number(), harvestShare: z.number(), allCoffeeShare: z.number(),
}));
export const ncrSchema = z.strictObject({
  path: z.string(),
  box: z.strictObject({ lon0: z.number(), lon1: z.number(), lat0: z.number(), lat1: z.number(), w: z.number(), h: z.number() }),
});
/** [lon, lat, name] */
export const osmLayerSchema = z.array(z.tuple([z.number(), z.number(), z.string()]));
